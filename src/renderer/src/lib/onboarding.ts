/**
 * ─── 首次引导的可见性判据（纯函数）────────────────────────────────────────────
 *
 * 审计 §7「首次引导 / 示例文档：无」：侧栏文件区在**没有任何工作区**时是**一片空白**
 * （用户口径：不放"新建文档 / 打开文件 / 打开文件夹"三个按钮 + 一行提示，已整块删除）。
 * 留白本身没错，但"第一次打开这个软件的人既看不到入口、也没有任何可点的东西"是缺口：
 * 菜单里有入口，可他得先知道菜单在哪。
 *
 * 这一版把引导**收窄成一个空态块**：只有"没有任何工作区、也没有真正在编辑的东西"
 * 才出现，有工作区或有文档时必然消失（判据就是下面这个纯函数，单测逐条钉住）。
 *
 * 为什么"空白未命名缓冲"也算"没有文档"：
 *   `main.ts` 启动时**总是**补一份未命名空白缓冲占位（见那里的时序说明），所以
 *   "没有工作区 + 一份谁都还没动过的空白缓冲"正是**第一次打开软件**的样子。
 *   若把 `hasDoc` 直接当成"有没有缓冲"，这块引导在真实启动路径上**永远不出现** ——
 *   那就等于把审计缺口换个地方留着。
 *
 * 反过来，任何一条"用户确实开始干了"的信号都会让它消失：
 *   * 打开了工作区（`root`）—— 文件区已经有内容了；
 *   * 缓冲区里已经有内容（草稿恢复、粘贴进来的文字……）—— 那是他的文档；
 *   * 文档有磁盘路径（打开/新建/另存过的文件）—— 那更是他的文档。
 */
export function shouldShowOnboarding(input: {
  /** 当前工作区根目录（null = 没打开任何文件夹） */
  root: string | null | undefined
  /** 编辑器里当前有没有文档（`files.current` 是否存在） */
  hasDoc: boolean
  /** 当前文档的磁盘路径（null = 未命名缓冲）；没有文档时传 null */
  path?: string | null
  /** 当前缓冲区的正文；"空白"判据只看它有没有非空白字符 */
  content?: string | null
}): boolean {
  // 有工作区 → 引导必须消失（文件区里有真的东西可点）
  if (input.root) return false
  // 没有任何文档 → 显示（此时编辑器区也是空的）
  if (!input.hasDoc) return true
  // 有文档但它已经落在磁盘路径上 → 那是用户在编辑的文件，不显示
  if (input.path) return false
  // 未命名缓冲：动过（内容里出现非空白字符）就当"已经在写了"，不显示
  return !(input.content ?? '').trim()
}

/**
 * 内置示例文档（`onboarding.sampleDoc`）的键。
 *
 * 值是**整篇 Markdown 原文**，三份语言包各一份（不是界面文案的碎片拼接）：
 * 它就是"插进缓冲区里的一份文档"，整篇地翻译才读得通 —— 标题、正文、代码注释
 * 都得跟着语言走。约定与测试见 `tests/onboarding.test.mjs`（它逐份读三份包，
 * 钉住"非空 + 块结构完整 + 不带会误触输入规则的裸标记"）。
 *
 * ⚠️ 那份原文里**不能出现** `{` `}` `@` 与裸 `|`（表格分隔那几行除外）：
 * 它要经过 vue-i18n 的消息编译，那三个字符分别是插值 / 链接 / 复数分隔符，
 * 轻则整条消息编译失败、重则那句文案变成"原始 key"。写成常量而不是字面量插在
 * 组件里，就是为了让"这条约定"有一个能被单测指到的名字。
 */
export const SAMPLE_DOC_KEY = 'onboarding.sampleDoc'
