// ─── 外部改动冲突（审计 §2 P1）──────────────────────────────────────────────
//
// 保存前主进程会比对"我们上次读/写这份文件时的 mtime"与磁盘现状（见 ipc.ts 的 file:write）。
// 不一致 = 在我们编辑期间有别的程序改过它（git 切分支 / 同步盘 / 另一个编辑器）。
//
// 这时候只有用户能决定怎么办，三件事都值得给出口：
//   * **覆盖** —— 我这份是我要的（手动保存时弹的二选一里选"仍要保存"）；
//   * **另存为** —— 两份都要（通知卡片上的按钮）；
//   * **重新打开** —— 放弃我的改动、以磁盘那份为准（通知卡片上的按钮）。
//
// 为什么"另存为 / 重新打开"做成**通知卡片上的按钮**而不是把确认框扩成三选一：
// 确认框（ui.confirm）只有两键，扩成多键要动模态组件与一批无障碍断言，属于独立改动。
// 而通知中心本来就支持可交互按钮（见 lib/notificationActions.ts），两条出路放在那里
// 既不用改模态，也**不会丢**：卡片一直留在通知中心里，用户什么时候决定都行。
/** 可交互通知的 kind（payload.kind = 这个值时由 useAppActions 注册的处理器接手） */
export const SAVE_CONFLICT_KIND = 'save-conflict'
